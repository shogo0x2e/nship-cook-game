import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
import {createSessionServer} from '../server/server.ts';

const app=await createSessionServer({port:0});await app.listen();
const base=`http://127.0.0.1:${app.server.address().port}`;
const browser=await chromium.launch({channel:process.env.E2E_BROWSER??'chrome',headless:true,args:['--disable-background-timer-throttling','--disable-renderer-backgrounding','--disable-backgrounding-occluded-windows']});
const page=await browser.newPage({viewport:{width:820,height:1180},hasTouch:true});
const errors=[],external=[],checks=[];
page.setDefaultTimeout(15000);page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(!r.url().startsWith(base+'/')&&!r.url().startsWith('blob:'))external.push(r.url());});
const check=name=>{checks.push(name);console.log(`PASS ${name}`);};
const click=action=>page.locator(`[data-action="${action}"]`).click();
const snapshot=async()=>{const r=await page.request.get(`${base}/api/family`);assert.equal(r.status(),200);return (await r.json()).state;};
await mkdir('test-results/challenge',{recursive:true});
try{
  const registered=await page.request.post(`${base}/api/auth/register`,{headers:{Origin:base},data:{username:`trial_${Date.now()}`,password:'poc4'}});assert.equal(registered.status(),201);
  await page.goto(base);await click('role-child');
  await click('variant-challenge');await click('start-demo');
  await page.getByRole('heading',{name:'45秒、好きな食材をキャッチ。'}).waitFor();
  await page.locator('[data-game="start"]').click();
  await page.waitForFunction(()=>Number(document.querySelector('#field')?.dataset.activeMs)>1000);
  await page.locator('[data-game="pause"]').click();
  const frozen=await page.locator('#field').getAttribute('data-active-ms');
  await page.waitForTimeout(1300);assert.equal(await page.locator('#field').getAttribute('data-active-ms'),frozen);
  await page.locator('[data-game="resume"]').click();
  const box=await page.locator('#field').boundingBox();await page.mouse.move(box.x+box.width*.3,box.y+box.height*.5);
  await page.waitForFunction(()=>Number(document.querySelector('#live-score')?.textContent.replaceAll(',',''))>0,{},{timeout:15000});
  await page.screenshot({path:'test-results/challenge/01-playing-portrait.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  await page.setViewportSize({width:1180,height:820});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  const wide=await page.locator('#field').boundingBox();await page.mouse.move(wide.x+wide.width*.3,wide.y+wide.height*.5);
  await page.screenshot({path:'test-results/challenge/02-playing-landscape.png',fullPage:true});
  check('challenge selection, countdown, live score, paused timer and responsive layouts');
  await page.locator('.challenge-result').waitFor({timeout:60000});
  const state=await snapshot(),run=state.challenge.runs[0];
  assert.equal(run.completed,true);assert.equal(run.activeMs,45000);assert.ok(run.caught>9);assert.ok(run.score>0);
  assert.equal(state.challenge.best[run.comparisonKey],run.score);
  await page.setViewportSize({width:820,height:1180});await page.waitForTimeout(500);await page.screenshot({path:'test-results/challenge/03-personal-best.png',fullPage:true});
  check('timed round continues beyond nine catches and persists a completed personal best');
  await page.locator('.daily-feedback summary').click();await page.locator('#daily-frequency').selectOption('weekly');
  await page.locator('#daily-reason').fill('夕ごはんの前なら使えそう。');await page.locator('#test-age').selectOption('middle');await page.locator('#test-fun').selectOption('4');
  await page.locator('#challenge-feedback button').click();await page.getByText('回答を保存しました。',{exact:true}).waitFor();
  await page.reload();await page.locator('.challenge-result').waitFor();
  assert.equal((await snapshot()).challenge.runs[0].feedback.frequency,'weekly');
  await page.locator('.daily-feedback summary').click();assert.equal(await page.locator('#daily-reason').inputValue(),'夕ごはんの前なら使えそう。');
  await page.screenshot({path:'test-results/challenge/04-daily-use-feedback.png',fullPage:true});
  check('daily-use intention, reason, optional school group and enjoyment survive reload');
  await click('start-demo');await page.locator('[data-game="start"]').click();await page.locator('[data-game="finish"]').click();
  await page.getByText('途中の記録は、自己ベストには含めません。',{exact:true}).waitFor();
  const after=await snapshot();assert.equal(after.challenge.runs.length,2);assert.equal(after.challenge.best[run.comparisonKey],run.score);
  await click('variant-simple');await click('start-demo');assert.equal(await page.locator('.challenge-hud').count(),0);
  assert.match(await page.locator('#counter').innerText(),/おさら.*1.*3/);
  await page.locator('[data-game="start"]').click();await page.locator('[data-game="finish"]').click();
  await page.getByRole('heading',{name:'食材を、大人に届けたよ！',exact:true}).waitFor();assert.equal((await snapshot()).challenge.runs.length,2);
  check('early exits cannot replace a best; preschool game keeps its three-plate rules');
  await click('switch-role');await click('role-adult');await page.locator('.challenge-records summary').click();
  const downloadPromise=page.waitForEvent('download');await click('export-challenge');const download=await downloadPromise;
  const exported=JSON.parse(await readFile(await download.path(),'utf8'));assert.equal(exported.runs.length,2);assert.equal(exported.runs[0].feedback.ageGroup,'middle');
  await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  check('trial records export without external requests or runtime errors');
  await writeFile('test-results/challenge/report.json',JSON.stringify({passed:checks.length,checks,realCamera:false,firstRun:{score:run.score,catches:run.caught},runtimeErrors:errors},null,2));
}finally{await browser.close();app.server.closeAllConnections();await new Promise(resolve=>app.server.close(resolve));}
