import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import { createSessionServer } from '../server/server.ts';

const app = await createSessionServer({port:0}); await app.listen();
const base = `http://127.0.0.1:${app.server.address().port}`;
const browser = await chromium.launch({channel:process.env.E2E_BROWSER ?? 'chrome',headless:true,args:['--disable-background-timer-throttling','--disable-renderer-backgrounding','--disable-backgrounding-occluded-windows']});
const page = await browser.newPage({viewport:{width:1180,height:900}});
const errors=[],requests=[],checks=[];
page.on('pageerror',e=>errors.push(e.message)); page.on('request',r=>requests.push({url:r.url(),method:r.method()}));
await page.addInitScript(()=>{navigator.mediaDevices.getUserMedia=async()=>{throw new DOMException('Synthetic denial','NotAllowedError');};});
const check=name=>{checks.push(name);console.log(`PASS ${name}`);};
const caught=()=>page.locator('#plates i:not(:empty)').count();
const pose=value=>page.locator('#sample-pose').selectOption(value);
const topPixels=()=>page.locator('#game-canvas').evaluate(canvas=>{const data=canvas.getContext('2d').getImageData(0,0,canvas.width,Math.floor(canvas.height*.28)).data; let hash=2166136261; for(const n of data)hash=Math.imul(hash^n,16777619);return hash;});
await mkdir('test-results/avatar',{recursive:true});
try {
  await page.goto(`${base}/poc.html`);
  await page.waitForFunction(()=>document.querySelector('#field')?.dataset.tracked==='true'&&!document.querySelector('#start-button').disabled);
  await pose('left'); await page.locator('[data-game="start"]').click();
  await page.waitForFunction(()=>document.querySelectorAll('#plates i:not(:empty)').length===1,{},{timeout:15000});
  await page.screenshot({path:'test-results/avatar/01-reaching-landscape.png',fullPage:true});
  check('generated sprites and synthetic face render; raised hand catches exactly one ingredient');
  await pose('lost'); await page.waitForFunction(()=>document.querySelector('#field')?.dataset.tracked==='false');
  assert.match(await page.locator('#tracking-note').innerText(),/時間は止まっている/);
  const count=await caught(), pixels=await topPixels(); await page.waitForTimeout(1300);
  assert.equal(await caught(),count); assert.equal(await topPixels(),pixels);
  await page.screenshot({path:'test-results/avatar/02-tracking-lost.png',fullPage:true});
  await pose('down'); await page.waitForFunction(()=>document.querySelector('#field')?.dataset.tracked==='true');
  await page.waitForTimeout(6500); assert.equal(await caught(),count);
  check('lost tracking freezes the round; lowered hands let a pair pass without catching');
  await page.locator('[data-game="pause"]').click();
  await page.getByRole('heading',{name:'ひとやすみ'}).waitFor();
  await page.setViewportSize({width:820,height:1180});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  await pose('left'); await page.locator('[data-game="resume"]').click();
  await page.locator('.tracking-debug summary').click();
  await page.waitForFunction(()=>document.querySelector('#pose-metrics')?.textContent.includes('タッチできます'));
  await page.screenshot({path:'test-results/avatar/03-portrait-diagnostics.png',fullPage:true});
  await page.locator('.tracking-debug summary').click();
  check('pause/resume, tablet rotation and local shoulder/elbow/wrist diagnostic view');
  await pose('both');
  await page.locator('#preview-evidence').waitFor({state:'attached',timeout:90000});
  const evidence=JSON.parse(await page.locator('#preview-evidence').textContent());
  assert.equal(Object.values(evidence).reduce((n,v)=>n+v.caught,0),9);
  assert.equal(Object.values(evidence).reduce((n,v)=>n+v.offered,0),18);
  for(const v of Object.values(evidence)){assert.deepEqual(Object.keys(v).sort(),['caught','offered']);assert.ok(v.caught<=v.offered);}
  check('even with both hands, three plates total nine catches and eighteen offers; skipped pairs excluded');
  await page.locator('[data-mode="sample"]').click();
  await page.waitForFunction(()=>document.querySelector('#field')?.dataset.tracked==='true');
  const oldStream=await page.locator('#camera').evaluateHandle(video=>video.srcObject);
  await page.locator('[data-mode="demo"]').click();
  assert.equal(await oldStream.evaluate(stream=>stream.getTracks().every(track=>track.readyState==='ended')),true);
  await page.locator('[data-game="start"]').click();
  await page.locator('[data-game="finish"]').click();
  await page.locator('[data-mode="camera"]').click();
  await page.locator('[data-game="prepare-camera"]').click();
  await page.getByText('カメラが許可されていません',{exact:false}).waitFor({timeout:30000});
  assert.equal(await page.locator('#start-button').isDisabled(),true);
  check('switching modes releases stream tracks; camera refusal stays recoverable; basket mode retained');
  assert.deepEqual(errors,[]);
  assert.deepEqual(requests.filter(r=>!r.url.startsWith(base+'/')||r.method!=='GET'||r.url.includes('/api/')),[]);
  check('no runtime errors, external requests or API writes; all pose/face processing remains local');
  await writeFile('test-results/avatar/report.json',JSON.stringify({passed:checks.length,checks,realCamera:false,realTablet:false,syntheticPose:true,runtimeErrors:errors.length,externalRequests:0,apiWrites:0},null,2));
} finally { await browser.close(); app.server.closeAllConnections(); await new Promise(resolve=>app.server.close(resolve)); }
